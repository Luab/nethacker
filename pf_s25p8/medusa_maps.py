def char_at(name, y, x):
    """The map character of variant `name` at screen (y, x); ' ' (solid rock) outside the map."""
    yoff, rows = MAPS[name]
    my, mx = y - yoff, x - XOFF
    if 0 <= my < len(rows) and 0 <= mx < len(rows[my]):
        return rows[my][mx]
    return ' '


def match(known_water, known_dry):
    """(variant, mismatches, compared) of the variant whose moat squares agree best with what the bot has seen:
    known_water / known_dry are iterables of screen (y, x) the bot knows to be water / not water."""
    best = None
    for name in MAPS:
        bad = n = 0
        for y, x in known_water:
            n += 1
            bad += char_at(name, y, x) != '}'
        for y, x in known_dry:
            n += 1
            bad += char_at(name, y, x) == '}'
        if best is None or bad < best[1]:
            best = (name, bad, n)
    return best
